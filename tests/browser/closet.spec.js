import { test, expect } from '@playwright/test';
import path from 'node:path';
import { enableAI } from './ai-test-support.js';
const photo=path.resolve('dress-code-studio/assets/look-travel-refined.png');
test('main entry, photo upload, persistent wardrobe and delete',async({page})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/dress-code-studio/');
 await expect(page.getByRole('button',{name:/내 옷 (AI 분석|등록)/})).toBeVisible();
 await page.screenshot({path:'test-results/closet-main.png',fullPage:true});
 await page.getByRole('button',{name:/갖고 있는 옷을 사진으로|내 옷, 어디에/}).click();
 const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();
 await expect(page.getByRole('button',{name:'AI로 분석하기'})).toBeDisabled();
 await page.locator('#closet-file').setInputFiles(photo);
 await expect(page.locator('#closet-preview')).toBeVisible();
 await page.locator('#closet-name').fill('나들이 니트');
 await page.getByRole('button',{name:'내 옷에 저장',exact:true}).click();
 await expect(page.getByRole('button',{name:'나들이 니트 불러오기'})).toBeVisible();
 await page.reload();await page.getByRole('button',{name:/내 옷 (AI 분석|등록)/}).click();
 await page.getByRole('button',{name:'나들이 니트 불러오기'}).click();
 await expect(page.locator('#closet-name')).toHaveValue('나들이 니트');
 await expect(page.getByRole('button',{name:'AI로 분석하기'})).toBeDisabled();
 await expect(page.locator('.closet-status')).toContainText('현재 지원되지 않는 기능입니다');
 await expect(page.locator('.closet-results')).toBeEmpty();
 await page.getByRole('button',{name:'나들이 니트 삭제'}).click();
 await expect(page.locator('.closet-empty')).toBeVisible();
 await page.getByRole('button',{name:'내 옷 분석 닫기'}).click();
 await expect(dialog).not.toBeVisible();expect(errors).toEqual([]);
});
test('analysis response renders safely, mobile layout and escape',async({page})=>{
 await enableAI(page);
 await page.setViewportSize({width:390,height:844});await page.goto('/dress-code-studio/');
 await page.getByRole('button',{name:/내 옷 (AI 분석|등록)/}).click();
 await page.locator('#closet-file').setInputFiles(photo);
 await expect(page.getByRole('button',{name:'AI로 분석하기'})).toBeEnabled();
 await page.locator('#closet-occasion').selectOption({label:'친구 모임'});
 let payload;
 await page.route('**/api/analyze-outfit',async route=>{payload=route.request().postDataJSON();await route.fulfill({json:{title:'차분한 니트 스타일',summary:'<img src=x onerror=alert(1)>',features:['니트','차콜 팬츠'],occasions:[{name:'친구 모임',fit:'잘 어울려요',reason:'편안한 모임에 좋아요.'}],targetAdvice:'지금 조합을 활용해 보세요.',tips:['편한 신발을 더해보세요.'],caution:'사진에 보이는 의상 기준의 참고 의견이에요.'}})});
 await page.getByRole('button',{name:'AI로 분석하기'}).click();
 await expect(page.getByRole('heading',{name:'차분한 니트 스타일'})).toBeVisible();
 expect(payload.image).toMatch(/^data:image\/jpeg;base64,/);expect(payload.occasion).toBe('친구 모임');
 await expect(page.locator('.closet-results img')).toHaveCount(0);
 expect(await page.locator('.closet-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
 await page.screenshot({path:'test-results/closet-mobile-result.png',fullPage:true});
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();
});
test('invalid upload and pending analysis cancellation',async({page})=>{
 await enableAI(page);
 await page.goto('/dress-code-studio/');await page.getByRole('button',{name:/내 옷 (AI 분석|등록)/}).click();
 await page.locator('#closet-file').setInputFiles({name:'invalid.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg/>')});
 await expect(page.locator('.closet-status')).toContainText('JPG, PNG, WEBP');
 await page.locator('#closet-file').setInputFiles(photo);
 await expect(page.getByRole('button',{name:'AI로 분석하기'})).toBeEnabled();
 await page.route('**/api/analyze-outfit',async route=>{await new Promise(resolve=>setTimeout(resolve,500));await route.fulfill({status:503,json:{error:'테스트: 분석 연결 준비 중'}}).catch(()=>{});});
 await page.getByRole('button',{name:'AI로 분석하기'}).click();
 await expect(page.locator('#closet-occasion')).toBeDisabled();
 await page.keyboard.press('Escape');await page.getByRole('button',{name:/내 옷 (AI 분석|등록)/}).click();
 await expect(page.getByRole('button',{name:'AI로 분석하기'})).toBeEnabled();
 await expect(page.locator('#closet-occasion')).toBeEnabled();
});
